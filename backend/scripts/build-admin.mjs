import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {Script} from 'node:vm';
const html=readFileSync(new URL('../worker/admin.html',import.meta.url),'utf8');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
if(scripts.length!==1)throw new Error('Admin page must contain exactly one inline script');
new Script(scripts[0][1]);
const hash='sha256-'+createHash('sha256').update(scripts[0][1]).digest('base64');
writeFileSync(new URL('../worker/admin-page.js',import.meta.url),'// Generated by npm run build:admin. Edit admin.html.\nexport const ADMIN_HTML='+JSON.stringify(html)+';\nexport const ADMIN_SCRIPT_HASH='+JSON.stringify(hash)+';\n');
